#!/usr/bin/env python3
"""Generate the homepage hero's decorative network (an abstract graph; it depicts no data).

Run after changing the layout or colors:  python3 scripts/make_motif.py
Writes _hero-motif.md, an inline SVG that index.qmd includes. The SVG is inline (not an <img>) so
the page's CSS can animate it and the hero's pause button can stop it. Animations live in
styles/site.scss and run only under .rr-motion (JS present, reduced motion not requested):
  * .rr-halo   hub halos breathe slowly;
  * .rr-signal short warm segments travel along selected edges, like activity passing through.
Without motion the signals stay hidden and the network is static. The layout is seeded, so it is
the same on every run.
"""
from __future__ import annotations

import math
import random
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "_hero-motif.md"
W, H = 760, 560
N_NODES = 46
N_SIGNALS = 12
# batlow[160], [192], [224], [240]: the warm end of Crameri's batlow map (as in the hero accent).
HEAT = ["#C09036", "#F29D6D", "#FDB4B6", "#FCC0D8"]
NEUTRAL = "#DDDDDD"   # grayC[30]


def layout(rnd: random.Random):
    nodes = []
    while len(nodes) < N_NODES:
        x, y = rnd.uniform(30, W - 30), rnd.uniform(30, H - 30)
        # Denser toward the lower right, where the motif sits behind the portrait.
        if rnd.random() < (x / W) * (y / H) * 1.6 + 0.12 and all(math.dist((x, y), n) > 46 for n in nodes):
            nodes.append((x, y))
    edges = set()
    for i, a in enumerate(nodes):
        for j in sorted(range(len(nodes)), key=lambda k: math.dist(a, nodes[k]))[1:4]:
            if math.dist(a, nodes[j]) < 150:
                edges.add(tuple(sorted((i, j))))
    return nodes, sorted(edges)


def main() -> int:
    rnd = random.Random(7)   # same seed as the original static motif: identical layout
    nodes, edges = layout(rnd)
    hubs = [k for k in range(len(nodes)) if k % 9 == 0]

    # Signals start at a hub and run outward along its longer edges, then along other long edges.
    def length(e):
        return math.dist(nodes[e[0]], nodes[e[1]])
    from_hubs = sorted((e for e in edges if e[0] in hubs or e[1] in hubs), key=length, reverse=True)
    others = sorted((e for e in edges if e not in from_hubs and length(e) > 70), key=length, reverse=True)
    signal_edges = (from_hubs + others)[:N_SIGNALS]
    if len(signal_edges) < N_SIGNALS:
        raise SystemExit(f"only {len(signal_edges)} edges qualify for signals, expected {N_SIGNALS}")

    out = [f'<svg class="rr-hero-motif" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" '
           f'aria-hidden="true" focusable="false">',
           '<g stroke="#FFFFFF" stroke-opacity="0.16" stroke-width="1">']
    out += [f'<line x1="{nodes[i][0]:.1f}" y1="{nodes[i][1]:.1f}" x2="{nodes[j][0]:.1f}" y2="{nodes[j][1]:.1f}"/>'
            for i, j in edges]
    out.append('</g>')

    # Signals: pathLength="1" lets one CSS animation fit every edge length. Durations and delays
    # are spread so that only a few travel at any moment.
    out.append('<g fill="none" stroke-width="1.6" stroke-linecap="round">')
    for n, (i, j) in enumerate(signal_edges):
        a, b = (nodes[i], nodes[j]) if i in hubs else (nodes[j], nodes[i])
        dur = 7.0 + (n * 1.37) % 4.5
        delay = -((n * 2.9) % dur)
        out.append(f'<path class="rr-signal" d="M{a[0]:.1f} {a[1]:.1f}L{b[0]:.1f} {b[1]:.1f}" pathLength="1" '
                   f'stroke="{HEAT[n % len(HEAT)]}" style="--rr-dur:{dur:.2f}s;--rr-delay:{delay:.2f}s"/>')
    out.append('</g><g>')
    for k, (x, y) in enumerate(nodes):
        hub = k in hubs
        c = HEAT[k % len(HEAT)] if hub or k % 3 == 0 else NEUTRAL
        if hub:
            out.append(f'<circle class="rr-halo" cx="{x:.1f}" cy="{y:.1f}" r="11" fill="{c}" fill-opacity="0.12" '
                       f'style="--rr-delay:{-(k * 0.7) % 6:.2f}s"/>')
        out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{4.2 if hub else 2.2}" fill="{c}" '
                   f'fill-opacity="{0.95 if hub else 0.6}"/>')
    out.append('</g></svg>')

    OUT.write_text("<!-- Generated by scripts/make_motif.py. Do not edit by hand. -->\n```{=html}\n"
                   + "\n".join(out) + "\n```\n", encoding="utf-8")
    print(f"{OUT.name}: {len(nodes)} nodes, {len(edges)} edges, {len(hubs)} hubs, {len(signal_edges)} signals, "
          f"{OUT.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
